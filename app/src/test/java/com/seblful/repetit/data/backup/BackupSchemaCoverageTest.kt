package com.seblful.repetit.data.backup

import com.seblful.repetit.data.local.ClassEntity
import com.seblful.repetit.data.local.GroupEntity
import com.seblful.repetit.data.local.GroupMemberCrossRef
import com.seblful.repetit.data.local.PaymentEntity
import com.seblful.repetit.data.local.PriceEntity
import com.seblful.repetit.data.local.RateChangeEntity
import com.seblful.repetit.data.local.StudentEntity
import com.seblful.repetit.data.local.StudentSubjectCrossRef
import com.seblful.repetit.data.local.SubjectEntity
import kotlinx.serialization.KSerializer
import kotlinx.serialization.descriptors.StructureKind
import kotlinx.serialization.descriptors.elementNames
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File

/**
 * Pins the backup snapshot to the actual schema.
 *
 * The snapshot has to track the entities, but [BackupData], [BackupManager] and the database's entity
 * list are three lists kept in step by hand — so adding a table or a column used to reach production
 * with every backup test still passing, silently absent from every backup. These tests derive their
 * expectations from the **exported schema JSON** (the same artifact the migration test validates
 * against, generated by Room from the entities), so a new table has to be acknowledged here before
 * the suite goes green again.
 */
class BackupSchemaCoverageTest {

    /**
     * Every table the snapshot carries, and the entity that carries it.
     *
     * This map is the acknowledgement. Add a table to the database and the first test below fails
     * until the table is either listed here — so it reaches the backup — or named in [deviceLocal]
     * on purpose.
     */
    private val carried: Map<String, KSerializer<*>> = mapOf(
        "subjects" to SubjectEntity.serializer(),
        "students" to StudentEntity.serializer(),
        "student_subjects" to StudentSubjectCrossRef.serializer(),
        "student_groups" to GroupEntity.serializer(),
        "group_members" to GroupMemberCrossRef.serializer(),
        "prices" to PriceEntity.serializer(),
        "price_history" to RateChangeEntity.serializer(),
        "classes" to ClassEntity.serializer(),
        "payments" to PaymentEntity.serializer(),
    )

    /**
     * Tables deliberately left out of the snapshot. Settings are device-local (notification and
     * calendar choices belong to the device, not the data), so restoring a backup must not carry
     * another device's preferences over.
     */
    private val deviceLocal = setOf("settings")

    @Test
    fun `every table in the schema is either carried by the snapshot or deliberately device-local`() {
        assertEquals(
            "A table exists that the snapshot neither carries nor deliberately excludes — " +
                "add it to `carried` (so backups include it) or to `deviceLocal` (on purpose).",
            schemaTables.keys.sorted(),
            (carried.keys + deviceLocal).sorted(),
        )
    }

    @Test
    fun `every column of a carried table survives serialization`() {
        carried.forEach { (table, serializer) ->
            val columns = schemaTables.getValue(table)
            val serialized = serializer.descriptor.elementNames.toSet()
            val lost = columns - serialized
            assertEquals(
                "Columns of `$table` are persisted but not serialized, so a backup would drop them",
                emptySet<String>(),
                lost,
            )
        }
    }

    @Test
    fun `the snapshot carries exactly the entities this test claims it does`() {
        // Ties `carried` to BackupData itself, so the map above cannot quietly fall behind the
        // snapshot it is meant to describe.
        val descriptor = BackupData.serializer().descriptor
        val inSnapshot = (0 until descriptor.elementsCount)
            .map { descriptor.getElementDescriptor(it) }
            .filter { it.kind == StructureKind.LIST }
            .map { it.getElementDescriptor(0).serialName }
            .toSet()
        assertEquals(
            "BackupData's lists and this test's `carried` map disagree",
            carried.values.map { it.descriptor.serialName }.toSet(),
            inSnapshot,
        )
    }

    // ---- the exported schema -----------------------------------------------------------------

    /** Table name → its column names, read from the newest exported schema JSON. */
    private val schemaTables: Map<String, Set<String>> by lazy {
        val database = Json.parseToJsonElement(newestSchemaFile().readText())
            .jsonObject.getValue("database").jsonObject
        database.getValue("entities").jsonArray.associate { entity ->
            val o = entity.jsonObject
            o.getValue("tableName").jsonPrimitive.content to
                o.getValue("fields").jsonArray
                    .map { it.jsonObject.getValue("columnName").jsonPrimitive.content }
                    .toSet()
        }
    }

    /**
     * The highest-versioned schema JSON under the module's `schemas/` directory. Walks up from the
     * working directory so it doesn't matter whether tests run from the module or the repo root.
     */
    private fun newestSchemaFile(): File {
        val workingDir = System.getProperty("user.dir") ?: "."
        var dir: File? = File(workingDir).absoluteFile
        while (dir != null) {
            val schemas = listOf(File(dir, "schemas"), File(dir, "app/schemas")).firstOrNull { it.isDirectory }
            if (schemas != null) {
                return schemas.walkTopDown()
                    .filter { it.isFile && it.extension == "json" }
                    .maxByOrNull { it.nameWithoutExtension.toIntOrNull() ?: -1 }
                    ?: error("No exported schema JSON under $schemas")
            }
            dir = dir.parentFile
        }
        error("Could not find the exported schemas directory from ${System.getProperty("user.dir")}")
    }
}
