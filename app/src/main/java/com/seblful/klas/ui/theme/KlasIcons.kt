private fun symbol(name: String, vararg pathData: String, autoMirror: Boolean = false): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 960f,
        viewportHeight = 960f,
        autoMirror = autoMirror,
    ).apply {
        addGroup(translationY = 960f)
        pathData.forEach { addPath(addPathNodes(it), fill = SolidColor(Color.Black)) }
        clearGroup()
    }.build()
