"""Write the medium- and high-contrast schemes: uv run art/contrast_schemes.py.

Material's contrast levels (0.5 and 1.0) applied to the palettes of the curated standard scheme in
Color.kt — its light keys for the light schemes, its dark accents for the dark ones, so the dark
containers keep their lower chroma. Error always takes the light key: the dark one is a pale tone
whose palette has too little chroma to make a red container.
"""

import re
from pathlib import Path

from materialyoucolor.dynamiccolor.color_spec import get_spec
from materialyoucolor.dynamiccolor.dynamic_scheme import DynamicScheme
from materialyoucolor.dynamiccolor.variant import Variant
from materialyoucolor.hct import Hct
from materialyoucolor.palettes.tonal_palette import TonalPalette

THEME = Path(__file__).parent.parent / "app/src/main/java/com/seblful/klas/ui/theme"
SPEC = get_spec("2021")

# Every role of `lightColorScheme`/`darkColorScheme` the spec defines, in that order.
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
    "surfaceTint", "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim",
    "surfaceBright", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "surfaceContainerLow", "surfaceContainerLowest", "surfaceDim",
    "primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
    "secondaryFixed", "secondaryFixedDim", "onSecondaryFixed", "onSecondaryFixedVariant",
    "tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed", "onTertiaryFixedVariant",
]
LEVELS = {"Medium": 0.5, "High": 1.0}


def curated() -> dict[str, int]:
    source = (THEME / "Color.kt").read_text(encoding="utf-8")
    return {m[1]: int(m[2], 16) for m in re.finditer(r"val (md_\w+) = Color\(0x(\w{8})\)", source)}


def palette(argb: int) -> TonalPalette:
    return TonalPalette.from_hct(Hct.from_int(argb))


def scheme(keys: dict[str, int], dark: bool, contrast: float, primary: str = "primary") -> DynamicScheme:
    suffix = "_d" if dark else ""

    def key(role: str) -> TonalPalette:
        return palette(keys[f"md_{role}{suffix}"])

    return DynamicScheme(
        Hct.from_int(keys[f"md_{primary}{suffix}"]),
        Variant.TONAL_SPOT,
        contrast,
        dark,
        spec_version="2021",
        primary_palette=key(primary),
        secondary_palette=key("secondary"),
        tertiary_palette=key("tertiary"),
        neutral_palette=key("surfaceContainer"),
        neutral_variant_palette=key("outline"),
        error_palette=palette(keys["md_error"]),
    )


def color(s: DynamicScheme, role: str) -> str:
    name = "primary" if role == "surfaceTint" else role
    return f"Color(0x{getattr(SPEC, name)().get_argb(s) & 0xFFFFFFFF:08X})"


def main() -> None:
    keys = curated()
    out = [
        "// Generated by `uv run art/contrast_schemes.py` from Color.kt's standard palettes. Do not edit.",
        "package com.seblful.klas.ui.theme",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.ui.graphics.Color",
    ]
    for dark in (False, True):
        mode = "Dark" if dark else "Light"
        for level, contrast in LEVELS.items():
            s = scheme(keys, dark, contrast)
            out += ["", f"internal val {mode}{level}ContrastScheme = {mode.lower()}ColorScheme("]
            out += [f"    {role} = {color(s, role)}," for role in ROLES]
            success = scheme(keys, dark, contrast, "success")
            live = scheme(keys, dark, contrast, "live")
            out += [
                ")",
                "",
                f"internal val {mode}{level}KlasColors = KlasColors(",
                f"    success = {color(success, 'primary')},",
                f"    successContainer = {color(success, 'primaryContainer')},",
                f"    onSuccessContainer = {color(success, 'onPrimaryContainer')},",
                f"    live = {color(live, 'primary')},",
                f"    isDark = {str(dark).lower()},",
                ")",
            ]
    (THEME / "ContrastColors.kt").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
